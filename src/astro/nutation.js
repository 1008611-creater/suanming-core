/** 1 弧度 = 多少角秒 */
export const ARCSEC_PER_RADIAN = 206264.80624709636;

/** 1 度 = 多少角秒 */
export const ARCSEC_PER_DEGREE = 3600;

/**
 * 章动的日月基本角（度）。
 * @param {number} T 儒略世纪数（TT，相对 J2000.0）
 * @returns {{D:number, M:number, Mp:number, F:number, Om:number}}
 */
export function fundamentalArguments(T) {
  return {
    // 月球与太阳的平距角
    D:  297.85036 + 445267.111480 * T - 0.0019142 * T * T + T * T * T / 189474,
    // 太阳平近点角
    M:  357.52772 + 35999.050340 * T - 0.0001603 * T * T - T * T * T / 300000,
    // 月球平近点角
    Mp: 134.96298 + 477198.867398 * T + 0.0086972 * T * T + T * T * T / 56250,
    // 月球升交点平角距
    F:   93.27191 + 483202.017538 * T - 0.0036825 * T * T + T * T * T / 327270,
    // 月球升交点黄经
    Om: 125.04452 - 1934.136261 * T + 0.0020708 * T * T + T * T * T / 450000
  };
}

const DEG_TO_RAD = Math.PI / 180;

/**
 * 章动分量。
 * @param {number} jde TT 儒略日
 * @returns {{dpsi:number, deps:number}} 黄经章动 dpsi 与交角章动 deps，单位：度
 */
export function nutation(jde) {
  const T = (jde - 2451545.0) / 36525;
  const a = fundamentalArguments(T);
  let dpsi = 0; // 0.0001 角秒
  let deps = 0;
  for (let i = 0; i < NUTATION_IAU1980.length; i++) {
    const row = NUTATION_IAU1980[i];
    const arg = (row[0] * a.D + row[1] * a.M + row[2] * a.Mp + row[3] * a.F + row[4] * a.Om) * DEG_TO_RAD;
    dpsi += (row[5] + row[6] * T) * Math.sin(arg);
    deps += (row[7] + row[8] * T) * Math.cos(arg);
  }
  return {
    dpsi: dpsi / 10000 / ARCSEC_PER_DEGREE,
    deps: deps / 10000 / ARCSEC_PER_DEGREE
  };
}

/** 黄经章动 Δψ（度） */
export function nutationInLongitude(jde) {
  return nutation(jde).dpsi;
}

/** 交角章动 Δε（度） */
export function nutationInObliquity(jde) {
  return nutation(jde).deps;
}

/**
 * 平黄赤交角 ε0（度）。Laskar 多项式（Meeus 22.3），对 ±10000 年有效。
 * @param {number} T 儒略世纪数（TT，相对 J2000.0）
 */
export function meanObliquity(T) {
  return 23.4392911111 - 0.0130041667 * T - 1.63889e-7 * T * T + 5.03611e-7 * T * T * T;
}

/** 真黄赤交角 ε = ε0 + Δε（度） */
export function trueObliquity(jde) {
  const T = (jde - 2451545.0) / 36525;
  return meanObliquity(T) + nutationInObliquity(jde);
}
